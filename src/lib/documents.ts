/**
 * Документы, которые приносит человек.
 *
 * Два места, откуда они берутся, и оба нужны:
 *   — клиент прикладывает материалы к своему окну (отчёт, выгрузка, договор);
 *   — администратор кладёт агенту постоянные документы (методика, стандарт,
 *     шаблон), и их видит каждый клиент этого агента.
 *
 * Файл живёт на сервере в РФ рядом с перепиской. Наружу к модели уходит либо
 * распознанный текст, либо сам файл — если модель умеет читать его как есть.
 */

/** Как файл поедет к модели. */
export type DocKind =
  /** PDF — отдаём модели целиком: она видит вёрстку, таблицы и подписи */
  | "pdf"
  /** Картинка — отдаём как изображение */
  | "image"
  /** Офисный документ — распознаём текст при загрузке */
  | "office"
  /** Обычный текст — берём как есть */
  | "text";

export type StoredFile = {
  id: string;
  /** Имя, как его назвал человек: показываем и отдаём при скачивании */
  name: string;
  /** Откуда приехал, если его не приносили руками: адрес ссылки */
  source?: string;
  mime: string;
  size: number;
  kind: DocKind;
  at: string;
  /** Сколько текста распознали. Ноль у PDF и картинок — их читает сама модель */
  chars: number;
  /** Что пошло не так при распознавании — честно показываем в интерфейсе */
  note: string;
};

// ── Пределы ───────────────────────────────────────────────────────────────────
// Пределов на самом деле два, и они про разное — их путают чаще всего.
//   1. Сколько модель удержит в голове за один вопрос. Это про окно модели и
//      меряется токенами (ниже — MAX_REQUEST_TOKENS и производный от него
//      знаковый потолок MAX_TEXT_CHARS).
//   2. Сколько весит сам HTTP-запрос к API. Это 32 МБ, и сколько бы ни было
//      окна, запрос тяжелее просто не доедет (ниже — MAX_RAW_BYTES).
// Второй предел не двигается вслед за первым. Лучше сказать об этом при
// загрузке, чем оборвать ответ на полуслове.

export const MAX_FILE_BYTES = 100 * 1024 * 1024;
export const MAX_WINDOW_FILES = 15;
export const MAX_AGENT_FILES = 10;
/** Сколько всего весят документы одного окна — чтобы диск не рос без спроса */
export const MAX_WINDOW_BYTES = 400 * 1024 * 1024;
export const MAX_AGENT_BYTES = 200 * 1024 * 1024;
/**
 * Картинку модель принимает маленькой — это её предел, не наш каприз.
 * Тяжёлое фото проще пересохранить, чем спорить с API.
 */
export const MAX_IMAGE_BYTES = 5 * 1024 * 1024;
/**
 * До этого размера PDF уезжает к модели файлом — она читает вёрстку и таблицы
 * своими глазами. Выше начинается предел запроса (32 МБ на всё), поэтому
 * большой PDF мы распознаём в текст у себя.
 */
export const MAX_PDF_NATIVE_BYTES = 25 * 1024 * 1024;
// ── Окно модели ───────────────────────────────────────────────────────────────

/** Окно claude-opus-5. Проверено по справке API, а не по памяти. */
export const MODEL_WINDOW_TOKENS = 1_000_000;
/** Потолок ответа у той же модели: столько окна занимает не вопрос, а ответ. */
export const MODEL_OUTPUT_TOKENS = 128_000;
/**
 * Сколько токенов может занять сам вопрос со всем, что к нему приложено:
 * инструкция агента, история переписки, документы.
 *
 * Из миллиона вычитаем ответ (128 тысяч) и ещё 32 тысячи запаса — на служебную
 * разметку блоков и на то, что счётчик считает запрос до наших последних
 * добавок. Запас маленький нарочно: он не должен съедать окно, он должен
 * спасать от промаха на границе.
 */
export const MAX_REQUEST_TOKENS = MODEL_WINDOW_TOKENS - MODEL_OUTPUT_TOKENS - 32_000;
/**
 * Знаков на токен для русского текста — осторожная оценка.
 *
 * Мера грубая и честно грубая: русская проза даёт около трёх знаков на токен,
 * таблица цифр — меньше полутора. Поэтому знаками мы только прикидываем, а
 * перед отправкой считаем настоящим счётчиком (server-llm.ts).
 */
export const CHARS_PER_TOKEN = 2.5;
/**
 * Сколько распознанного текста уедет к модели за один вопрос.
 *
 * Раньше здесь стояло 300 000 знаков. Потолок достался от прежних моделей с
 * окном в 200 тысяч токенов, и с тех пор его никто не пересчитывал: годовой
 * отчёт занимал в новом окне десятую часть, а мы резали его по старой мерке —
 * и разбор строился на половине цифр, причём человек об этом не знал.
 *
 * Откуда взялись полтора миллиона. Из MAX_REQUEST_TOKENS (840 тысяч) вычитаем
 * то, что в запросе уже занято и текстом документов быть не может:
 *    20 000 токенов — инструкция агента (двадцать пять тысяч знаков);
 *   120 000 — история переписки, несколько длинных ответов агента подряд;
 *   100 000 — PDF и картинки: они едут файлами и в знаках не меряются вовсе.
 * Остаётся 600 000 токенов, по 2,5 знака на токен — полтора миллиона знаков,
 * около семисот страниц текста.
 *
 * Это грубый предварительный фильтр, а не приговор. Что не поместилось в один
 * запрос, платформа дочитывает по частям (server-llm.ts): полтора миллиона —
 * это ровно MAX_DOC_PARTS × PART_CHARS, то есть самый большой документ, какой
 * мы беремся прочитать целиком, пусть и в несколько заходов.
 */
export const MAX_TEXT_CHARS = 1_500_000;
/**
 * Сколько «сырых» байт (PDF, картинки) влезает в один запрос.
 *
 * Эту цифру нельзя поднимать вслед за окном модели, и соблазн велик. 24 МБ
 * здесь — не про окно, а про размер HTTP-запроса к API: его предел 32 МБ, а
 * base64 раздувает файл на треть, и остаётся ещё обвязка. Дадут модели хоть
 * десять миллионов токенов — запрос тяжелее 32 МБ всё равно не доедет.
 */
export const MAX_RAW_BYTES = 24 * 1024 * 1024;
/**
 * На сколько частей разрешено разрезать один документ, если он не влез.
 *
 * Шесть. Каждая часть — отдельный вопрос к модели, и они идут по очереди, а не
 * разом: восемь частей превратили бы один вопрос в четверть часа ожидания, а
 * столько не стоит ни один разбор. Шесть частей по 250 тысяч знаков — это
 * полтора миллиона, ровно MAX_TEXT_CHARS: больше к нам и не доедет.
 */
export const MAX_DOC_PARTS = 6;
/**
 * Размер одной части при чтении по частям.
 *
 * 250 тысяч знаков — это около ста тысяч токенов: такой запрос модель
 * переваривает быстро, и если один из шести сорвётся, потеряна будет шестая
 * часть работы, а не вся.
 */
export const PART_CHARS = 250_000;

// ── Что принимаем ─────────────────────────────────────────────────────────────

const byExt: Record<string, DocKind> = {
  pdf: "pdf",
  png: "image",
  jpg: "image",
  jpeg: "image",
  gif: "image",
  webp: "image",
  docx: "office",
  xlsx: "office",
  pptx: "office",
  txt: "text",
  md: "text",
  csv: "text",
  tsv: "text",
  json: "text",
  xml: "text",
  log: "text",
};

const imageMime: Record<string, string> = {
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  gif: "image/gif",
  webp: "image/webp",
};

export const extOf = (name: string) => (name.split(".").pop() ?? "").toLowerCase();

export const kindOf = (name: string): DocKind | null => byExt[extOf(name)] ?? null;

/** Тип для модели: она проверяет media_type строго, на глазок сюда нельзя. */
export function mimeOf(name: string, fallback: string): string {
  const ext = extOf(name);
  if (ext === "pdf") return "application/pdf";
  if (imageMime[ext]) return imageMime[ext]!;
  return fallback || "application/octet-stream";
}

export const SUPPORTED_HINT = "PDF, Word, Excel, PowerPoint, текст, CSV, картинки";

/** Почему файл не приняли — словами, которые можно показать человеку. */
export function rejectReason(name: string, size: number): string {
  if (!kindOf(name)) {
    const ext = extOf(name);
    if (ext === "doc" || ext === "xls" || ext === "ppt") {
      return `${name}: старый формат Office. Пересохраните как .${ext}x — и загрузится`;
    }
    return `${name}: такой формат не читается. Принимаем ${SUPPORTED_HINT}`;
  }
  if (size > MAX_FILE_BYTES)
    return `${name}: ${humanSize(size)} — больше ${humanSize(MAX_FILE_BYTES)}`;
  if (kindOf(name) === "image" && size > MAX_IMAGE_BYTES) {
    return `${name}: картинка тяжелее ${humanSize(MAX_IMAGE_BYTES)} — модель такую не примет, пересохраните поменьше`;
  }
  if (size === 0) return `${name}: файл пустой`;
  return "";
}

/** Готовое вложение для запроса к модели. */
export type Attachment = {
  title: string;
  kind: DocKind;
  /** Распознанный текст — для офисных и текстовых файлов */
  text: string;
  /** Сам файл — для PDF и картинок, их модель читает своими глазами */
  base64: string;
  mime: string;
  /** Чей документ: постоянный у агента или принесённый человеком */
  origin: "agent" | "person";
};

export function humanSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} Б`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} КБ`;
  return `${(bytes / 1024 / 1024).toFixed(1).replace(".", ",")} МБ`;
}

/**
 * Влезут ли документы в один вопрос агенту.
 *
 * Пределов два, и они не складываются: распознанный текст меряется знаками,
 * а PDF с картинками уезжают файлами и меряются байтами. Поэтому и считаем
 * две суммы отдельно.
 *
 * Оценка приблизительная и нарочно осторожная. Тот же бюджет занимают
 * постоянные документы агента — методика, шаблон, — а их человек в своём
 * списке не видит и посчитать не может. Значит, предупреждение сработает не
 * всегда, когда документы не поместились; зато соврать в другую сторону —
 * напугать там, где всё уехало целиком, — оно не должно, поэтому никакого
 * запаса «на всякий случай» мы сюда не закладываем.
 *
 * И порог тут теперь мягкий: не влезло в один запрос — не значит потеряно.
 * Что не помещается, агент дочитывает по частям, просто дольше обычного.
 * Эта проверка предупреждает о другом: документов столько, что даже по частям
 * их за один вопрос не прочесть.
 */
export function requestFit(files: StoredFile[]): {
  fits: boolean;
  overText: boolean;
  overRaw: boolean;
} {
  let chars = 0;
  let bytes = 0;
  for (const f of files) {
    if (f.kind === "office" || f.kind === "text") chars += f.chars;
    else bytes += f.size;
  }
  const overText = chars > MAX_TEXT_CHARS;
  const overRaw = bytes > MAX_RAW_BYTES;
  return { fits: !overText && !overRaw, overText, overRaw };
}

/** Одна строка про файл под его именем: размер и что с ним стало. */
export function fileNote(f: StoredFile): string {
  const bits: string[] = [];
  if (f.size) bits.push(humanSize(f.size));

  if (f.note) bits.push(f.note);
  else if (f.kind === "pdf") {
    // Большой PDF модель файлом не принимает — мы распознали его сами.
    bits.push(
      f.chars
        ? `PDF, распознано ${f.chars.toLocaleString("ru-RU")} знаков`
        : "PDF, агент читает целиком",
    );
  } else if (f.kind === "image") bits.push("изображение");
  else if (!f.chars) bits.push("текста не нашлось");
  else bits.push(`${f.chars.toLocaleString("ru-RU")} знаков текста`);

  if (f.source) bits.push("по ссылке");
  return bits.join(" · ");
}
