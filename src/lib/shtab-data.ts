/**
 * Каталог агентов.
 *
 * Агент — это собеседник по одной задаче. Работа с ним начинается с выбора:
 * человек видит, кто с ним может работать, выбирает — и открывается окно.
 * Подключать агента к пустому окну нельзя: окно без агента бессмысленно.
 *
 * Пока это заглушки: имена и обещание результата. Настоящая работа
 * появится вместе с бэкендом платформы.
 */

