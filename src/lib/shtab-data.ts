/**
 * Каталог агентов.
 *
 * Агент — это собеседник по одной задаче. Работа с ним начинается с выбора:
 * человек видит, кто с ним может работать, выбирает — и открывается разговор.
 *
 * У агента две подписи, и обе обязательны. Имя без должности ничего не говорит:
 * «Никита» рядом со «Счетоводом» и «Стейкхолдерами» читается как случайность,
 * а руководителю, который видит этот экран восемь минут, нужно понять состав
 * команды с одного взгляда. И третья строка — что принести: без неё разговор
 * начинается с того, что агент просит материалы, а человек уже закрыл вкладку.
 */

export type Agent = {
  id: string;
  /** Имя агента — как его зовут в разговоре */
  name: string;
  /** Должность: по одному имени непонятно, чем он занят */
  role: string;
  /** Что человек получит на руки */
  result: string;
  /** Одна строка про то, как он работает */
  method: string;
  /** Что принести, чтобы разговор не начался с просьбы прислать материалы */
  needs: string;
};

