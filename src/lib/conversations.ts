/**
 * Окно — один разговор с одним агентом.
 *
 * Окно принадлежит агенту с рождения и не меняет его: работа идёт по задаче,
 * а не «переключением собеседника». Всё, что агент собрал в этом окне —
 * разбор, документ, решение, — остаётся здесь же. И документы, которые принёс
 * человек, тоже живут здесь: они относятся к этой задаче, а не ко всем сразу.
 */
import type { StoredFile } from "./documents";

export type Speaker = "user" | "agent";

export type StoredMessage = {
  id: string;
  from: Speaker;
  text: string;
  at: string;
  /**
   * От лица какой роли шёл разговор. Пусто у обычных агентов.
   *
   * У агента с ролями окно одно, а разговоров в нём несколько — по одному
   * на роль. История каждой роли отдельная: логист не должен отвечать на
   * вопросы, заданные финансисту, и не должен видеть, как участник перед
   * ним оправдывался.
   */
  roleId?: string;
  /**
   * Приписка платформы к этому ответу: «агент прочитал не всё» и подобное.
   * Живёт на сообщении, а не в летучей полосе: человек, открывший разговор
   * назавтра, должен видеть, по какой части документа сделан разбор.
   */
  note?: string;
};

/** Материал окна: готовый документ, который агент собрал по ходу работы. */
export type WindowDoc = {
  id: string;
  title: string;
  kind: string;
  at: string;
  /** Какой ответ агента лёг в основу: по нему собирается файл Word */
  messageId?: string;
};

export type StoredWindow = {
  id: string;
  agentId: string;
  /**
   * В какой папке идёт работа. У окон, открытых до появления папок, поля нет —
   * им папку заводят при первом чтении (см. readWorkspace).
   */
  projectId?: string;
  /** Заголовок — первый вопрос человека: список читается без открытия */
  title: string;
  messages: StoredMessage[];
  docs: WindowDoc[];
  /**
   * Документы этого окна и только его.
   *
   * Общие материалы задачи лежат в папке — их видит любой агент проекта.
   * Сюда попадает то, что человек принёс именно этому собеседнику: обычно
   * чужой разбор, взятый из проекта кнопкой «взять из проекта».
   */
  files: StoredFile[];
  /**
   * Состав согласующих: id ролей, по которым человек решил прогнать документ.
   *
   * Состав живёт у разговора, а не у задачи, потому что защищают перед людьми
   * не задачу целиком, а конкретный документ: инвестиционный расчёт несут
   * финансам и коммерческому, а схему доставки — логистике и категории. Один
   * состав на всю задачу означал бы, что второй документ идёт по чужим людям.
   *
   * Пусто или поля нет — состав ещё не набран; это не «взять всех по
   * умолчанию»: кого звать, решает человек, а не платформа.
   */
  panel?: string[];
  createdAt: string;
  updatedAt: string;
};

export const shortTitle = (s: string) => (s.length <= 46 ? s : s.slice(0, 45).trimEnd() + "…");
