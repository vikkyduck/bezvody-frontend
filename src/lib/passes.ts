/**
 * Сборка документа в четыре прогона.
 *
 * Разговор с агентом и сборка документа — разная работа. В разговоре агент
 * ведёт человека по шпаргалке и доводит фактуру: спрашивает, показывает дыры,
 * говорит, где взять цифру. Документ там не пишется. Когда фактуры хватает,
 * человек нажимает «Собрать документ» — и тогда запускается конвейер.
 *
 * Прогоны идут по очереди, каждый получает результат предыдущего:
 *   1. Сборка — самая сильная модель, задача полнота и точность;
 *   2. Язык — рерайт на деловой русский, без ИИ-штампов;
 *   3. Объём — усушка тела до шести страниц;
 *   4. Сверка — возврат искажённых чисел и источников.
 *
 * Почему не всё сразу одной моделью: у каждой работы свои требования, и
 * смешанные в одну инструкцию они мешают друг другу. «Пиши полно» и «уложись
 * в шесть страниц» в одном промпте дают документ, который не полон и не
 * короток. Разные модели ещё и видят чужие огрехи: то, что Opus считает
 * нормальной фразой, Gemini переписывает.
 *
 * Здесь значения по умолчанию. Методолог правит их в админке, и тогда в
 * agents.json ложится его список — этот файл остаётся запасным вариантом.
 * В браузер отсюда ничего не уезжает: промпты приходят администратору
 * ответом сервера, как и инструкции ролей.
 */
