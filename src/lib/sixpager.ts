export const TOTAL_QUESTIONS = SIXPAGER.reduce((n, s) => n + s.questions.length, 0);

/**
 * Шпаргалка текстом — такой её получает агент.
 *
 * Формат простой и плоский: агент читает документы текстом, и разметка ему
 * нужна только чтобы не слипались разделы. Вопросы нумеруются, чтобы агент
 * мог сослаться на конкретный: «закрыт вопрос 3 из FAQ-2».
 */
export function checklistAsText(): string {
  const parts = [
    "СТРУКТУРА 6-PAGER: РАЗДЕЛЫ И ВОПРОСЫ ПОД КАЖДЫЙ",
    "",
    "Структура одинакова для любого 6-pager: название, Executive summary, 4 раздела FAQ, " +
      "глоссарий, приложения. Меняются названия разделов — они формулируются как вопросы, " +
      "которые задаст читатель по этой конкретной теме. Роли разделов сквозные: где мы сейчас, " +
      "что узнали и что движет ростом, что нужно дальше, что делаем.",
    "",
    "Это рабочая шпаргалка методики. Веди разбор по ней: собирай документ по этим разделам, " +
      "проверяй ответы по этим вопросам и в разборе прямо называй, какие вопросы остались " +
      "без ответа — с номером раздела и номером вопроса.",
  ];

  for (const s of SIXPAGER) {
    parts.push("", `── ${s.num}. ${s.title}`, s.note);
    if (s.lead) parts.push(s.lead);
    parts.push("");
    s.questions.forEach((q, i) => parts.push(`${i + 1}. ${q}`));
    parts.push(`Что должно получиться: ${s.result}`);
  }

  return parts.join("\n");
}
