/**
 * Проект — папка одной задачи.
 *
 * До проектов окно было единицей работы: своё у каждого агента, со своими
 * документами. Один и тот же документ приходилось приносить трижды — сначала
 * Архитектору, потом Стейкхолдерам, потом Счетоводу, — и результаты лежали в
 * трёх разных местах. Проект собирает это в одну папку: документы кладутся
 * один раз и видны всем окнам проекта, а всё собранное копится здесь же.
 *
 * Что НЕ делается само: результат одного агента не подсовывается другому.
 * Шестистраничник Архитектора попадёт к Стейкхолдерам только если человек
 * сам нажмёт «взять из проекта» — он решает, кому что показывать.
 */
import type { StoredFile } from "./documents";

export type StoredProject = {
  id: string;
  /** Имя папки — его даёт человек: «Тариф M-сегмента» */
  title: string;
  /**
   * Документы задачи: отчёты, выгрузки, договоры. Общие для всех окон
   * проекта — их читает любой агент, к которому человек пришёл с этой задачей.
   */
  files: StoredFile[];
  createdAt: string;
  updatedAt: string;
  /**
   * Когда задачу закончили. Пусто — задача в работе.
   *
   * Это не удаление. Удаление уносит документы и разговоры разом и назад не
   * отыгрывается, поэтому и спрашивать «точно?» приходится всерьёз — а на
   * третьем месяце работы у человека тридцать задач, из которых половина
   * сделана, и он не станет ничего стирать, чтобы разгрести список. В итоге
   * лента росла, вчерашняя задача выглядела как сданная полгода назад, и
   * продукт начинал мешать ровно тем, кто им пользуется чаще всех.
   * «Закончил» — обычное рабочее действие, оно должно стоить один клик и
   * отыгрываться назад: работа остаётся целиком, задача просто уходит из
   * ленты активных.
   *
   * Поле необязательное: записи, сделанные до появления закрытия, его не
   * знают — и читаются как открытые (см. isProjectOpen).
   */
  closedAt?: string | null;
};

/**
 * Задача в работе, если её не закрывали.
 *
 * Отдельная функция, а не `!p.closedAt` по месту: значений у «не закрыта»
 * три — поля нет вовсе (старая запись), null (вернули в работу) и пустая
 * строка, — и проверять их порознь в каждом списке значит рано или поздно
 * потерять чью-то задачу из ленты.
 */
export const isProjectOpen = (p: StoredProject) => !p.closedAt;

/**
 * Столько открытых задач разом: дальше список перестаёт читаться.
 * Закрытые в счёт не идут — иначе человек, который аккуратно закрывает
 * сделанное, упирался бы в тот же потолок, что и тот, кто не закрывает.
 */
export const MAX_PROJECTS = 40;

export const DEFAULT_PROJECT_TITLE = "Новая задача";

/** Имя папки: без имени список превращается в «Новая задача, Новая задача…». */
export const cleanProjectTitle = (raw: string) => raw.trim().slice(0, 90);
