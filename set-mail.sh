#!/usr/bin/env bash
#
# Ящик, из которого платформа шлёт клиентам готовые разборы.
#
# Спрашивает пять вещей: сервер, порт, имя пользователя, пароль и адрес
# отправителя. Пароль вводится вслепую и уходит на сервер потоком ввода: он
# не попадает ни в историю команд, ни в список процессов, ни в журналы — ни
# здесь, ни там. Ложится в тот же secrets.json, что и ключи моделей, с
# правами 600 и владельцем bezvody.
#
#   ./set-mail.sh              — настроить или поменять ящик
#   ./set-mail.sh --убрать     — отключить почту (кабинет продолжит работать)
#
# Что взять у почтового провайдера:
#   · сервер и порт — у Яндекс 360 это smtp.yandex.ru и 465, у Mail.ru
#     smtp.mail.ru и 465. Порт 465 — это шифрование с первого байта, и
#     платформа умеет только его: см. server-mail.ts, там объяснено почему;
#   · пароль — НЕ пароль от почтового ящика, а «пароль приложения». У Яндекса
#     он делается в Яндекс ID → Безопасность → Пароли приложений → Почта, и
#     выглядит как шестнадцать букв. Обычный пароль современный провайдер для
#     почтовых программ не принимает, и ошибка будет невнятная — «сервер не
#     принял логин или пароль»;
#   · адрес отправителя должен совпадать с ящиком, из которого шлём. Чужой
#     адрес в отправителе провайдер отвергнет, даже если пароль верный, —
#     иначе с любого ящика можно было бы писать от чужого имени.
#
# Перезапускать сервис не нужно: настройки читаются с диска на каждое письмо.
#
# Если прямой маршрут до сервера не работает (так бывает: до Timeweb иногда
# ложится маршрут, при этом сам сервер жив), идём через дроплет:
#   BV_JUMP=root@206.189.181.64 ./set-mail.sh

set -euo pipefail

SERVER="${BV_SERVER:-root@5.129.198.180}"
JUMP="${BV_JUMP:-}"
SECRETS="/opt/bezvody-front-data/secrets.json"

HOST=""
PORT=""
USER_NAME=""
FROM=""
PASS=""

if [ "${1:-}" = "--убрать" ]; then
  MODE="убрать"
  echo "Отключаю почту. Разборы останутся в кабинете — письмами ходить перестанут."
else
  MODE="задать"

  read -rp "Сервер почты [smtp.yandex.ru]: " HOST
  HOST="${HOST:-smtp.yandex.ru}"

  read -rp "Порт [465]: " PORT
  PORT="${PORT:-465}"
  if ! [[ "$PORT" =~ ^[0-9]+$ ]]; then
    echo "Порт — это число. Обычно 465."
    exit 1
  fi
  if [ "$PORT" != "465" ]; then
    echo
    echo "Внимание: платформа умеет только шифрование с первого байта (порт 465)."
    echo "На 587 у большинства провайдеров разговор начинается открытым, и письмо"
    echo "просто не уйдёт. Если провайдер требует 587 — это доработка в server-mail.ts."
    echo
  fi

  read -rp "Имя пользователя (обычно полный адрес ящика): " USER_NAME
  if [ -z "$USER_NAME" ]; then
    echo "Пусто — ничего не меняю."
    exit 1
  fi

  read -rp "Адрес отправителя [$USER_NAME]: " FROM
  FROM="${FROM:-$USER_NAME}"

  # Вводится вслепую: -s не показывает набранное, echo возвращает перевод строки.
  printf 'Пароль приложения (не отображается): '
  read -rs PASS
  echo
  if [ -z "$PASS" ]; then
    echo "Пусто — ничего не меняю."
    exit 1
  fi

  echo
  echo "Сервер:      $HOST:$PORT"
  echo "Пользователь: $USER_NAME"
  echo "Отправитель: $FROM"
  echo "Пароль:      принят, ${#PASS} знаков (наружу не показываем)"
  echo
fi

# Программа уезжает на сервер закодированной в аргументе команды, а поток
# ввода остаётся свободным — по нему идёт пароль. Наоборот не выходит: если
# подать программу потоком, python съест его целиком и паролю места не
# останется. На этом соседний set-api-key.sh один раз уже молча записал
# пустоту, поэтому здесь так же и по той же причине.
PROG=$(base64 <<'PY' | tr -d '\n'
import json, os, sys

# rstrip только переводов строки: пробел на конце пароля — редкость, но он
# имеет право там быть, и молча его срезать нельзя.
password = sys.stdin.readline().rstrip("\n").rstrip("\r")
path = os.environ["SECRETS"]
mode = os.environ["MODE"]

try:
    with open(path) as f:
        data = json.load(f)
except FileNotFoundError:
    data = {}

if mode == "убрать":
    data.pop("mail", None)
    print("почта отключена")
else:
    data["mail"] = {
        "host": os.environ["HOST"],
        "port": int(os.environ["PORT"]),
        "user": os.environ["USER_NAME"],
        "pass": password,
        "from": os.environ["FROM"],
    }
    print("сервер:      %s:%s" % (data["mail"]["host"], data["mail"]["port"]))
    print("пользователь:", data["mail"]["user"])
    print("отправитель:", data["mail"]["from"])
    print("пароль:      записан, %d знаков" % len(password))

with open(path, "w") as f:
    json.dump(data, f, ensure_ascii=False, indent=2)
os.chmod(path, 0o600)

import shutil
shutil.chown(path, "bezvody", "bezvody")
PY
)

# Пароль — единственное, что идёт потоком. Остальное едет переменными
# окружения: в списке процессов они видны, но там нет ничего тайного.
printf '%s\n' "$PASS" | ssh ${JUMP:+-J "$JUMP"} "$SERVER" \
  "MODE='$MODE' HOST='$HOST' PORT='$PORT' USER_NAME='$USER_NAME' FROM='$FROM' SECRETS='$SECRETS' python3 -c 'import base64;exec(base64.b64decode(\"$PROG\"))'"

unset PASS

echo "Готово. Перезапускать ничего не надо — настройки подхватятся со следующего письма."
